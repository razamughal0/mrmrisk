import 'dotenv/config';
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { Pool } from 'pg';
import { drizzle } from 'drizzle-orm/node-postgres';
import { pgTable, serial, varchar } from 'drizzle-orm/pg-core';
import { eq } from 'drizzle-orm';
const base = process.env.TEST_URL || 'http://localhost:3000';
const fixtureTitle = 'Browser test: supportive check-in';
const pool = new Pool({ connectionString: process.env.DATABASE_URL });
const db = drizzle(pool);
const plans = pgTable('interventions', { id: serial('id').primaryKey(), title: varchar('title') });
async function cleanup() { await db.delete(plans).where(eq(plans.title, fixtureTitle)); }
await cleanup();
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base, { waitUntil: 'networkidle' });
  await page.getByRole('heading', { name: 'Students who could use a little support' }).waitFor();
  await page.waitForTimeout(300);
  await page.screenshot({ path: '/tmp/uplift-desktop.png', fullPage: true });
  console.log('PASS: Admin dashboard loaded');
  await page.getByRole('button', { name: "View Emma Wilson's record" }).click();
  await page.getByRole('heading', { name: 'What’s behind the score?' }).waitFor();
  await page.locator('#quiz-slider').focus();
  await page.locator('#quiz-slider').press('End');
  assert.equal(await page.locator('#quiz-slider').inputValue(), '100');
  await page.waitForTimeout(300);
  await page.screenshot({ path: '/tmp/uplift-student-detail.png', fullPage: true });
  await page.getByRole('button', { name: 'Close student profile' }).click();
  console.log('PASS: Student details and what-if slider work');
  await page.getByRole('button', { name: 'View all students' }).click();
  await page.getByRole('textbox', { name: 'Search student directory' }).fill('Emma Wilson');
  await page.getByRole('row').filter({ hasText: 'Emma Wilson' }).first().waitFor();
  console.log('PASS: Directory search works');
  await page.getByRole('button', { name: 'Switch demo workspace role' }).click();
  await page.getByRole('button', { name: 'Teacher / advisor Your courses. Your students.' }).click();
  await page.getByText('YOUR STUDENTS. YOUR IMPACT.', { exact: true }).waitFor();
  let workspace = await page.evaluate(async () => (await fetch('/api/workspace')).json());
  assert.equal(workspace.user.role, 'teacher');
  assert(workspace.students.every(s => ['Computer Science', 'Data Science'].includes(s.course)));
  console.log('PASS: Teacher sees assigned courses only');
  await page.getByRole('button', { name: 'New intervention', exact: true }).click();
  await page.locator('select[name="studentId"]').selectOption(String(workspace.students[0].id));
  await page.locator('input[name="title"]').fill(fixtureTitle);
  await page.locator('textarea[name="notes"]').fill('A practical check-in created by the automated smoke test.');
  await page.getByRole('button', { name: 'Create intervention', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'A new support plan is ready' }).waitFor();
  console.log('PASS: Teacher creates a saved intervention');
  await page.getByRole('button', { name: 'Switch demo workspace role' }).click();
  await page.getByRole('button', { name: 'Student Your record. Your way forward.' }).click();
  await page.getByRole('heading', { name: 'You’ve got this, Emma.' }).waitFor();
  workspace = await page.evaluate(async () => (await fetch('/api/workspace')).json());
  assert.equal(workspace.user.role, 'student');
  assert.equal(workspace.students.length, 1);
  const forbidden = await page.evaluate(async () => (await fetch('/api/interventions', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ studentId: 1 }) })).status);
  assert.equal(forbidden, 403);
  console.log('PASS: Student sees own record and cannot create interventions');
  await page.getByRole('button', { name: 'My support plan', exact: true }).click();
  await page.getByRole('heading', { name: fixtureTitle }).waitFor();
  const createdCard = page.locator('.intervention-card').filter({ hasText: fixtureTitle });
  await createdCard.getByRole('button', { name: 'Mark complete' }).click();
  await createdCard.getByText('One step forward').waitFor();
  console.log('PASS: Student sees and completes the new support plan');
  await page.screenshot({ path: '/tmp/uplift-student-workspace.png', fullPage: true });
  await page.getByRole('button', { name: 'Switch demo workspace role' }).click();
  await page.getByRole('button', { name: 'Administrator The whole student success picture' }).click();
  await page.getByRole('heading', { name: 'Student success, in focus.' }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(400);
  await page.screenshot({ path: '/tmp/uplift-mobile.png', fullPage: true });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('heading', { name: 'Make yourself at home.' }).waitFor();
  await page.getByRole('button', { name: 'Save preferences' }).click();
  await page.getByRole('status').filter({ hasText: 'Your preferences are saved' }).waitFor();
  console.log('PASS: Mobile navigation and persisted preferences work without page overflow');
  assert.deepEqual(errors, []);
  console.log('PASS: No browser runtime errors');
} finally { await browser.close(); await cleanup(); await pool.end(); }
